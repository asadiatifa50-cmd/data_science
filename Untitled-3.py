
grade=int(input("Enter your grade"))


if grade>=97 and grade<=100:
    print("Grade A+")

elif 93<=grade<=96:
    print("Grade A")

elif 90<=grade<=92:
    print("Grade A-")

elif 87<=grade<=89:
    print("Grade B+")

elif 83<=grade<=86:
    print("Grade B")

elif 80<=grade<=82:
    print("Grade B-")

elif 77<=grade<=79:
    print("Grade C+")

elif 73<=grade<=76:
    print("Grade C")

elif 70<=grade<=72:
    print("Grade C-") 

elif 67<=grade<=69:
    print("Grade D+")

elif 60<=grade<=66:
    print("Grade D")

else:
    print ("Fail")